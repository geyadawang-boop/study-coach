#!/usr/bin/env python3
"""Render Markdown views from append-only JSONL records.

records/ is the structured source of truth; views/ is generated and must not
be edited by hand. Re-run after every append.

Usage:
  python kb_view.py --kb 学习库
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

BANNER = "<!-- generated by scripts/kb_view.py; do not edit by hand -->"


def load(path: Path) -> tuple[list[dict], int]:
    rows: list[dict] = []
    skipped = 0
    if not path.exists():
        return rows, skipped
    with path.open(encoding="utf-8-sig") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                skipped += 1
                continue
            if isinstance(item, dict):
                rows.append(item)
            else:
                skipped += 1
    return rows, skipped


def text(value) -> str:
    if value is None:
        return "-"
    if isinstance(value, (list, tuple)):
        return "；".join(str(v) for v in value if str(v).strip()) or "-"
    return str(value).strip() or "-"


def count_of(value, default: int = 1) -> int:
    """坏 count（如「三次」）按默认值处理，视图不因单条记录崩溃。"""
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def card_block(card: dict) -> list[str]:
    cid = text(card.get("id"))
    title = text(card.get("title"))
    lines = [f"### {cid}｜{title}", ""]
    lines.append(f"- 识别信号：{text(card.get('signal'))}")
    lines.append(f"- 首选方法：{text(card.get('method'))}")
    steps = card.get("steps")
    if isinstance(steps, list) and steps:
        lines.append("- 标准步骤：" + " → ".join(str(s) for s in steps))
    else:
        lines.append(f"- 标准步骤：{text(steps)}")
    lines.append(f"- 适用边界：{text(card.get('boundary'))}")
    lines.append(f"- 代表真题：{text(card.get('evidence'))}")
    lines.append(f"- 关联易错点：{text(card.get('errors'))}")
    lines.append(f"- 状态：{text(card.get('status'))}")
    lines.append("")
    return lines


def render_cards(cards: list[dict], generated: str) -> str:
    verified = [c for c in cards if str(c.get("status", "")).lower() == "verified"]
    retired = [c for c in cards if str(c.get("status", "")).lower() == "retired"]
    hypothesis = [c for c in cards if c not in verified and c not in retired]
    lines = [BANNER, "", "# 题型定性卡片", "", f"生成时间：{generated}", ""]
    lines.append(f"数据源：`records/cards.jsonl`（共 {len(cards)} 张）")
    lines.append("")
    lines.append("## 已验证（verified）")
    lines.append("")
    if verified:
        for card in sorted(verified, key=lambda c: str(c.get("id", ""))):
            lines.extend(card_block(card))
    else:
        lines.extend(["_暂无_", ""])
    lines.append("## 待验证（hypothesis）")
    lines.append("")
    if hypothesis:
        for card in sorted(hypothesis, key=lambda c: str(c.get("id", ""))):
            lines.extend(card_block(card))
    else:
        lines.extend(["_暂无_", ""])
    if retired:
        lines.append("## 已退役（retired）")
        lines.append("")
        for card in sorted(retired, key=lambda c: str(c.get("id", ""))):
            lines.extend(card_block(card))
    return "\n".join(lines)


def render_errors(errors: list[dict], generated: str) -> str:
    active = [e for e in errors if str(e.get("status", "open")).lower() != "closed"]
    by_chapter: dict[str, list[dict]] = defaultdict(list)
    for item in active:
        by_chapter[text(item.get("chapter"))].append(item)

    lines = [BANNER, "", "# 易错点汇总", "", f"生成时间：{generated}", ""]
    lines.append(f"数据源：`records/errors.jsonl`（活跃 {len(active)} 条，已闭环 {len(errors) - len(active)} 条）")
    lines.append("")
    lines.append("| ID | 章节 | 错误描述 | 后果 | 正确做法 | 次数 | 首次 | 状态 |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for chapter in sorted(by_chapter):
        items = sorted(by_chapter[chapter], key=lambda e: (-count_of(e.get("count", 1)), str(e.get("id", ""))))
        for item in items:
            lines.append(
                f"| {text(item.get('id'))} | {chapter} | {text(item.get('desc'))} "
                f"| {text(item.get('consequence'))} | {text(item.get('fix'))} "
                f"| {text(item.get('count', 1))} | {text(item.get('first_seen'))} "
                f"| {text(item.get('status', 'open'))} |"
            )
    if not active:
        lines.append("| - | - | 暂无记录 | - | - | - | - | - |")
    lines.append("")
    return "\n".join(lines)


def render_sources(sources: list[dict], generated: str) -> str:
    labels = {"scope": "范围", "authority": "权威", "exam": "应试"}
    counts = {k: sum(1 for s in sources if str(s.get("layer")) == k) for k in labels}
    lines = [BANNER, "", "# 资料清单", "", f"生成时间：{generated}", ""]
    lines.append(
        f"数据源：`records/sources.jsonl`（共 {len(sources)} 份："
        f"范围 {counts['scope']} / 权威 {counts['authority']} / 应试 {counts['exam']}）"
    )
    lines.append("")
    lines.append("| ID | 标题 | 层 | 类型 | 信任 | 覆盖 | 来源 | 加入 |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    order = {"scope": 0, "authority": 1, "exam": 2}
    for item in sorted(sources, key=lambda s: (order.get(str(s.get("layer")), 9), str(s.get("id", "")))):
        layer = str(item.get("layer") or "")
        title = text(item.get("title"))
        if item.get("supersedes"):
            title += f"（替代 {item['supersedes']}）"
        lines.append(
            f"| {text(item.get('id'))} | {title} | {labels.get(layer, layer or '-')} "
            f"| {text(item.get('kind'))} | {text(item.get('trust'))} "
            f"| {text(item.get('coverage'))} | {text(item.get('source'))} "
            f"| {text(item.get('added_at'))} |"
        )
    if not sources:
        lines.append("| - | 暂无资料 | - | - | - | - | - | - |")
    lines.append("")
    lines.append("说明：本文件由 `records/sources.jsonl` 渲染，不手改；四标判定见 `references/source-layers.md`。")
    lines.append("")
    return "\n".join(lines)


def as_date(value) -> date | None:
    try:
        return date.fromisoformat(str(value or "")[:10])
    except ValueError:
        return None


LINK = re.compile(r"\[\[([^\]\|#]+)(?:#[^\]\|]*)?(?:\|[^\]]*)?\]\]")
NOTE_ID = re.compile(r"^([A-Z]+-\d+)")


def render_backlinks(
    kb: Path,
    cards: list[dict],
    errors: list[dict],
    confusions: list[dict],
    generated: str,
) -> tuple[str, int, int]:
    """Scan Markdown for [[...]] links and report inbound references.

    A link resolves to a note stem, a note ID prefix (LEC-003 →
    LEC-003-无穷小比较.md), a card, an error or a confusion. Anything else is
    reported as a broken link instead of being silently dropped.
    """
    notes: list[Path] = []
    for path in sorted(kb.rglob("*.md")):
        parts = path.relative_to(kb).parts
        if "views" in parts or any(part.startswith(".") for part in parts):
            continue
        if path.name == "02-资料清单.md":
            continue  # 派生视图，不当作笔记来源
        notes.append(path)

    stems = {path.stem for path in notes}
    id_prefix: dict[str, list[str]] = defaultdict(list)
    for stem in stems:
        match = NOTE_ID.match(stem)
        if match:
            id_prefix[match.group(1)].append(stem)
    known_ids = {
        str(item.get("id")) for item in (*cards, *errors, *confusions) if item.get("id")
    }

    inbound: dict[str, list[tuple[str, int]]] = defaultdict(list)
    for path in notes:
        rel = path.relative_to(kb).as_posix()
        for no, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for raw in LINK.findall(line):
                target = raw.strip()
                if target:
                    inbound[target].append((rel, no))

    def resolved(target: str) -> bool:
        return target in stems or target in id_prefix or target in known_ids

    broken = [target for target in inbound if not resolved(target)]
    lines = [BANNER, "", "# 双链反查", "", f"生成时间：{generated}", ""]
    lines.append("派生视图，不手改。链接约定见 `references/knowledge-base.md`。")
    lines.append("")
    lines.append(f"- 被引用的目标：{len(inbound)}")
    lines.append(f"- 断链：{len(broken)}")
    lines.append("")
    lines.append("| 目标 | 引用次数 | 来源（文件:行） | 状态 |")
    lines.append("| --- | --- | --- | --- |")
    for target, places in sorted(inbound.items(), key=lambda item: (-len(item[1]), item[0])):
        where = "；".join(f"{rel}:{no}" for rel, no in places[:6])
        if len(places) > 6:
            where += f"；…共 {len(places)} 处"
        lines.append(
            f"| [[{target}]] | {len(places)} | {where} | {'有效' if resolved(target) else '断链'} |"
        )
    if not inbound:
        lines.append("| - | 0 | 暂无双链 | - |")
    lines.append("")
    lines.append("断链处理：改链接名，或在 `notes/` 新建对应文件；不要靠改视图层掩盖。")
    lines.append("")
    return "\n".join(lines), len(inbound), len(broken)


def render_snapshot(
    cards: list[dict],
    errors: list[dict],
    reviews: list[dict],
    events: list[dict],
    sources: list[dict],
    generated: str,
) -> str:
    today = date.today()
    verified = sum(1 for c in cards if str(c.get("status", "")).lower() == "verified")
    retired = sum(1 for c in cards if str(c.get("status", "")).lower() == "retired")
    hypothesis = len(cards) - verified - retired

    active_errors = [e for e in errors if str(e.get("status", "open")).lower() != "closed"]
    repeated = sorted(
        active_errors, key=lambda e: -count_of(e.get("count", 1))
    )[:8]

    latest: dict[str, tuple[tuple[str, str], dict]] = {}
    for review in reviews:
        card_id = str(review.get("card_id") or "")
        if not card_id:
            continue
        key = (str(review.get("ts") or ""), str(review.get("id") or ""))
        if card_id not in latest or key >= latest[card_id][0]:
            latest[card_id] = (key, review)

    overdue: list[tuple[date, str]] = []
    due_soon: list[tuple[date, str]] = []
    for card_id, (_, review) in latest.items():
        due = as_date(review.get("due"))
        if due is None:
            continue
        if due < today:
            overdue.append((due, card_id))
        elif due <= today + timedelta(days=7):
            due_soon.append((due, card_id))
    overdue.sort()
    due_soon.sort()

    recent = [
        e for e in events
        if (when := as_date(e.get("ts"))) and when >= today - timedelta(days=6)
    ]
    actions: dict[str, int] = defaultdict(int)
    for event in recent:
        actions[str(event.get("action") or "?")] += 1
    tickets = [e for e in recent if str(e.get("action")) == "exit_ticket"]
    passed = sum(1 for e in tickets if str(e.get("result", "")).lower() == "pass")
    layers: dict[str, int] = defaultdict(int)
    for source in sources:
        layers[str(source.get("layer") or "?")] += 1

    lines = [BANNER, "", "# 学情快照", "", f"生成时间：{generated}", ""]
    lines.append("派生视图，不手改。掌握度与证据规则见 `references/knowledge-base.md`。")
    lines.append("")
    lines.append("## 卡片与复习")
    lines.append("")
    lines.append(f"- 卡片：已验证 {verified} / 待验证 {hypothesis} / 已退役 {retired}")
    lines.append(f"- 到期未复习：{len(overdue)}")
    for due, card_id in overdue[:5]:
        lines.append(f"  - {card_id} 到期 {due.isoformat()}")
    lines.append(f"- 未来 7 天到期：{len(due_soon)}")
    lines.append("")
    lines.append("## 错题")
    lines.append("")
    lines.append(f"- 未闭环 {len(active_errors)} / 已闭环 {len(errors) - len(active_errors)}")
    lines.append("")
    if repeated:
        lines.append("| ID | 章节 | 错误描述 | 次数 | 后果 |")
        lines.append("| --- | --- | --- | --- | --- |")
        for item in repeated:
            lines.append(
                f"| {text(item.get('id'))} | {text(item.get('chapter'))} "
                f"| {text(item.get('desc'))} | {text(item.get('count', 1))} "
                f"| {text(item.get('consequence'))} |"
            )
    else:
        lines.append("_暂无未闭环错题_")
    lines.append("")
    lines.append("## 最近 7 天")
    lines.append("")
    if recent:
        detail = "、".join(f"{name} {count}" for name, count in sorted(actions.items()))
        lines.append(f"- 事件 {len(recent)} 条：{detail}")
        lines.append(f"- 退出票：通过 {passed} / 未通过 {len(tickets) - passed}")
    else:
        lines.append("_最近 7 天无事件_")
    lines.append("")
    lines.append("## 资料")
    lines.append("")
    lines.append(
        f"- 范围 {layers.get('scope', 0)} / 权威 {layers.get('authority', 0)} "
        f"/ 应试 {layers.get('exam', 0)}"
    )
    lines.append("")
    if len(cards) < 5:
        lines.append("> 样本不足 5 张卡：只报证据数量，不报掌握度结论。")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kb", default=".", help="备考工作目录（含 records/ 与 views/）")
    args = parser.parse_args()

    kb = Path(args.kb)
    if not kb.is_dir():
        print(f"kb not found: {kb}", file=sys.stderr)
        return 2
    records = kb / "records"
    views = kb / "views"
    views.mkdir(parents=True, exist_ok=True)
    generated = datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %z")

    cards, skipped_cards = load(records / "cards.jsonl")
    errors, skipped_errors = load(records / "errors.jsonl")
    sources, skipped_sources = load(records / "sources.jsonl")
    reviews, skipped_reviews = load(records / "reviews.jsonl")
    events, skipped_events = load(records / "events.jsonl")
    confusions, skipped_confusions = load(records / "confusions.jsonl")

    def write_view(path: Path, text: str) -> None:
        if path.is_file():
            old = path.read_text(encoding="utf-8", errors="replace")
            if not old.startswith(BANNER):
                print(f"warning: {path} 曾被手改，已覆盖；views/ 只由脚本生成", file=sys.stderr)
        path.write_text(text, encoding="utf-8")

    backlink_text, targets, broken = render_backlinks(kb, cards, errors, confusions, generated)
    # 先全部渲染完再落盘：单张视图渲染失败时不留半新半旧的文件集
    rendered = [
        (views / "题型卡片.md", render_cards(cards, generated)),
        (views / "易错点汇总.md", render_errors(errors, generated)),
        (views / "学情快照.md",
         render_snapshot(cards, errors, reviews, events, sources, generated)),
        (views / "双链反查.md", backlink_text),
        (kb / "02-资料清单.md", render_sources(sources, generated)),
    ]
    for path, content in rendered:
        write_view(path, content)

    skipped = (
        skipped_cards + skipped_errors + skipped_sources + skipped_reviews
        + skipped_events + skipped_confusions
    )
    print(
        f"cards={len(cards)} errors={len(errors)} sources={len(sources)} "
        f"reviews={len(reviews)} events={len(events)} skipped={skipped} "
        f"backlinks={targets} broken_links={broken} out={views}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
