#!/usr/bin/env python3
"""Align the same content across two textbooks by semantic similarity.

Chapter titles are not a join key: two books can teach one knowledge point
under different headings, and identical headings (「本章小结」) often hold
different content. This script embeds each indexed chunk, compares every
main-book chunk against every other-book chunk by cosine, and reports
one-to-one pairs plus what each book covers alone.

The similarity score is a recall signal, not a verdict: pairs are banded as
同义覆盖 / 表述不同 / 低置信 and the caller still decides whether the two
passages teach the same thing.

Usage:
  python book_align.py index.db [--main 甲书] [--other 乙书] [--min-sim 0.68]
  python book_align.py index.db --json

Book prefixes match the first path segment under the knowledge base, so a
book imported as `甲书/第1章.md` is selected with `--main 甲书`.

Exit codes: 0 = 对齐完成；2 = 索引或分书不可用；3 = 缺嵌入缓存。
"""

from __future__ import annotations

import argparse
import json
import math
import operator
import re
import sys
from pathlib import Path

from kb_index import load_embeddings, open_index

BANNER = "<!-- generated by scripts/book_align.py; 语义对齐结果，不手改 -->"
MIN_SIM = 0.68
STRONG_SIM = 0.85
WEAK_SIM = 0.74
TOP_CANDIDATES = 3
PREVIEW = 90
# 结构块不是知识点：两本书的「本章小结」天然相似，配对上去只会噪音。
STRUCTURAL = re.compile(
    r"^(本章)?(小结|总结|要点|概览|习题|练习题|课后题|复习题|思考题|自测|检测|答案|索引|附录|前言|目录)$"
)
# 「1.3 小结」「第5章 小结」也是结构块，先去掉编号再判定。
HEADING_NOISE = re.compile(
    r"^(?:第[0-9一二三四五六七八九十百千]+[章节讲篇]\s*|[0-9]+(?:\.[0-9]+)*[.、]?\s*)+"
)


def book_of(path: str) -> str:
    parts = [part for part in path.split("/") if part]
    return parts[0] if len(parts) > 1 else "根目录"


def norm_prefix(value: str) -> str:
    return value.replace("\\", "/").strip("/")


def in_book(path: str, prefix: str) -> bool:
    prefix = norm_prefix(prefix)
    return bool(prefix) and (path == prefix or path.startswith(prefix + "/"))


def plain_heading(heading: str) -> str:
    parts = [part.strip() for part in heading.split(">") if part.strip()]
    return HEADING_NOISE.sub("", parts[-1]).strip() if parts else ""


def is_structural(row: dict) -> bool:
    plain = plain_heading(row["heading"])
    return bool(plain) and bool(STRUCTURAL.match(plain))


def load_chunks(conn) -> list[dict]:
    rows = conn.execute(
        "SELECT c.id, d.path, COALESCE(c.heading, ''), c.text, c.ord "
        "FROM chunks c JOIN docs d ON d.id = c.doc_id ORDER BY d.path, c.ord"
    ).fetchall()
    return [
        {"id": int(chunk_id), "path": path, "heading": heading,
         "text": text, "book": book_of(path)}
        for chunk_id, path, heading, text, _ord in rows
    ]


def pick_books(rows: list[dict], main: str | None,
               other: str | None) -> tuple[list[dict], list[dict], str, str]:
    """Split chunks into the two books; explicit prefixes win over auto-detect."""
    if bool(main) != bool(other):
        raise ValueError("--main 与 --other 必须同时给出")
    if main and other:
        if norm_prefix(main) == norm_prefix(other):
            raise ValueError("--main 与 --other 指向同一本书")
        left = [row for row in rows if in_book(row["path"], main)]
        right = [row for row in rows if in_book(row["path"], other)]
        if not left or not right:
            raise ValueError(f"分书为空：--main {main} 命中 {len(left)} 块，"
                             f"--other {other} 命中 {len(right)} 块")
        overlap = {row["id"] for row in left} & {row["id"] for row in right}
        if overlap:
            raise ValueError(f"分书重叠：{len(overlap)} 块同时命中两本书，"
                             "请给互不包含的路径前缀")
        return left, right, norm_prefix(main), norm_prefix(other)

    counts: dict[str, int] = {}
    for row in rows:
        counts[row["book"]] = counts.get(row["book"], 0) + 1
    if len(counts) != 2:
        listed = "、".join(f"{name}({count})" for name, count in counts.items()) or "无"
        raise ValueError(
            f"自动分书需要恰好两本教材，当前识别到：{listed}；"
            "请用 --main / --other 指定路径前缀"
        )
    names = list(counts)  # 按入库顺序，先见到的那本作主教材
    groups = {name: [row for row in rows if row["book"] == name] for name in names}
    first, second = names[0], names[1]
    if counts[second] > counts[first]:
        first, second = second, first  # 块数多的一方作主教材
    return groups[first], groups[second], first, second


def unit_norms(rows: list[dict], vectors: dict[int, list[float]]) -> list[float]:
    norms: list[float] = []
    for row in rows:
        vector = vectors.get(row["id"])
        norms.append(math.sqrt(sum(value * value for value in vector)) if vector else 0.0)
    return norms


def align(main_rows: list[dict], other_rows: list[dict],
          vectors: dict[int, list[float]], min_sim: float) -> list[dict]:
    """Greedy one-to-one matching over per-chunk top candidates."""
    other_norms = unit_norms(other_rows, vectors)
    candidates: list[tuple[float, int, int]] = []
    for index, row in enumerate(main_rows):
        vector = vectors.get(row["id"])
        if not vector:
            continue
        norm = math.sqrt(sum(value * value for value in vector))
        if not norm:
            continue
        scored: list[tuple[float, int]] = []
        for other_index, other_row in enumerate(other_rows):
            other_vector = vectors.get(other_row["id"])
            if not other_vector or len(other_vector) != len(vector):
                continue
            if not other_norms[other_index]:
                continue
            dot = sum(map(operator.mul, vector, other_vector))
            score = dot / (norm * other_norms[other_index])
            if score >= min_sim:
                scored.append((score, other_index))
        scored.sort(reverse=True)
        for score, other_index in scored[:TOP_CANDIDATES]:
            candidates.append((score, index, other_index))

    candidates.sort(key=lambda item: -item[0])
    used_main: set[int] = set()
    used_other: set[int] = set()
    matched: list[dict] = []
    for score, index, other_index in candidates:
        if index in used_main or other_index in used_other:
            continue
        used_main.add(index)
        used_other.add(other_index)
        matched.append({
            "main": main_rows[index],
            "other": other_rows[other_index],
            "sim": round(score, 4),
            "verdict": verdict_for(score),
        })
    matched.sort(key=lambda item: (item["main"]["path"], item["main"]["id"]))
    return matched


def verdict_for(score: float) -> str:
    if score >= STRONG_SIM:
        return "同义覆盖"
    if score >= WEAK_SIM:
        return "表述不同，核对是否同一知识点"
    return "低置信，需人工确认"


def where(row: dict) -> str:
    return f"{row['path']} › {row['heading']}" if row["heading"] else row["path"]


def preview(row: dict) -> str:
    text = " ".join(row["text"].split())
    return text[:PREVIEW] + ("…" if len(text) > PREVIEW else "")


def cell(text: str) -> str:
    """表格单元格里的竖线要转义，否则会多切出一列。"""
    return str(text).replace("|", "\\|")


def build(main_rows: list[dict], other_rows: list[dict], matched: list[dict],
          model: str, main: str, other: str, min_sim: float,
          structural: dict[str, int]) -> tuple[str, dict]:
    paired_main = {item["main"]["id"] for item in matched}
    paired_other = {item["other"]["id"] for item in matched}
    only_main = [row for row in main_rows if row["id"] not in paired_main]
    only_other = [row for row in other_rows if row["id"] not in paired_other]
    coverage_main = len(paired_main) / len(main_rows) if main_rows else 0.0
    coverage_other = len(paired_other) / len(other_rows) if other_rows else 0.0

    lines = [
        BANNER,
        "",
        f"# 双教材语义对照：{main} → {other}",
        "",
        f"> 按切块嵌入余弦对齐，不按章节名对齐。嵌入模型：`{model}`；阈值 {min_sim:.2f}。",
        "> 相似度只用于召回候选，最终是否同一知识点仍需人工或模型裁定。",
        "",
        "## 对齐结果",
        "",
        "| # | " + cell(main) + " | " + cell(other) + " | 相似度 | 判定 |",
        "| --- | --- | --- | --- | --- |",
    ]
    for index, item in enumerate(matched, 1):
        lines.append(
            f"| {index} | {cell(where(item['main']))} | {cell(where(item['other']))} "
            f"| {item['sim']:.3f} | {cell(item['verdict'])} |"
        )
    if not matched:
        lines.append("| - | 无达到阈值的配对 | - | - | - |")

    lines += ["", f"## 仅 {cell(main)} 覆盖", "", "| 位置 | 摘要 |", "| --- | --- |"]
    for row in only_main:
        lines.append(f"| {cell(where(row))} | {cell(preview(row))} |")
    if not only_main:
        lines.append("| - | 无 |")

    lines += ["", f"## 仅 {cell(other)} 覆盖", "", "| 位置 | 摘要 |", "| --- | --- |"]
    for row in only_other:
        lines.append(f"| {cell(where(row))} | {cell(preview(row))} |")
    if not only_other:
        lines.append("| - | 无 |")

    lines += [
        "",
        "## 自检",
        "",
        f"- 主教材 {len(main_rows)} 块，副教材 {len(other_rows)} 块，一对一配对 {len(matched)} 对。",
        f"- 跳过结构块：{main} {structural['main']} 块、{other} {structural['other']} 块"
        "（本章小结/习题等，不作为知识点对齐）。",
        f"- 覆盖率：{main} {coverage_main:.0%}，{other} {coverage_other:.0%}。",
        "- 同一块只进入一对；同一章节名内容不同时不会被强行配对。",
    ]

    summary = {
        "main": main,
        "other": other,
        "model": model,
        "minSim": min_sim,
        "mainChunks": len(main_rows),
        "otherChunks": len(other_rows),
        "pairs": [
            {
                "main": where(item["main"]),
                "other": where(item["other"]),
                "sim": item["sim"],
                "verdict": item["verdict"],
            }
            for item in matched
        ],
        "onlyMain": [where(row) for row in only_main],
        "onlyOther": [where(row) for row in only_other],
        "structural": structural,
        "coverage": {"main": round(coverage_main, 3), "other": round(coverage_other, 3)},
    }
    return "\n".join(lines) + "\n", summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("db", help="kb_index.py build 生成的索引")
    parser.add_argument("--main", help="主教材路径前缀（知识库下第一级目录）")
    parser.add_argument("--other", help="副教材路径前缀")
    parser.add_argument("--min-sim", type=float, default=MIN_SIM,
                        help=f"进入配对的最低余弦相似度，默认 {MIN_SIM}")
    parser.add_argument("--out", help="写入 Markdown（默认打印到标准输出）")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    if not math.isfinite(args.min_sim) or not 0.0 <= args.min_sim <= 1.0:
        print("--min-sim 必须是 0 到 1 之间的有限数", file=sys.stderr)
        return 2

    conn = open_index(Path(args.db))
    try:
        rows = load_chunks(conn)
        loaded = load_embeddings(Path(args.db), conn)
    finally:
        conn.close()
    if loaded is None:
        print("缺嵌入缓存：先跑 kb_index.py embed <db>（并配置嵌入后端）", file=sys.stderr)
        return 3
    vectors, meta = loaded

    try:
        main_rows, other_rows, main_name, other_name = pick_books(rows, args.main, args.other)
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 2

    structural = {
        "main": sum(1 for row in main_rows if is_structural(row)),
        "other": sum(1 for row in other_rows if is_structural(row)),
    }
    main_rows = [row for row in main_rows if not is_structural(row)]
    other_rows = [row for row in other_rows if not is_structural(row)]

    matched = align(main_rows, other_rows, vectors, args.min_sim)
    text, summary = build(
        main_rows, other_rows, matched, str(meta.get("model") or "unknown"),
        main_name, other_name, args.min_sim, structural,
    )

    if args.out:
        target = Path(args.out)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        if not args.json:
            print(f"wrote {target} pairs={len(matched)} "
                  f"main={len(main_rows)} other={len(other_rows)}")
    if args.json:
        print(json.dumps(summary, ensure_ascii=False, indent=2))
    elif not args.out:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
