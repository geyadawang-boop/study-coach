#!/usr/bin/env python3
"""Aggregate records/confusions.jsonl into a ranked Markdown table."""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path


def load(path: Path) -> tuple[dict[str, dict], int]:
    records: dict[str, dict] = defaultdict(
        lambda: {"count": 0, "kind": "", "chapter": "", "last": ""}
    )
    skipped = 0
    with path.open(encoding="utf-8-sig") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                skipped += 1
                continue
            tag = str(item.get("tag") or "").strip()
            if not tag:
                skipped += 1
                continue
            try:
                count = max(1, int(item.get("ask_count", 1)))
            except (TypeError, ValueError):
                count = 1
            row = records[tag]
            row["count"] += count
            row["kind"] = row["kind"] or str(item.get("kind") or "")
            row["chapter"] = row["chapter"] or str(item.get("chapter") or "")
            date = str(item.get("date") or "")
            if date > row["last"]:
                row["last"] = date
    return records, skipped


def render(records: dict[str, dict], top: int, source: Path) -> str:
    rows = sorted(records.items(), key=lambda kv: (-kv[1]["count"], kv[0]))[:top]
    lines = [
        "<!-- generated by scripts/kb_stats.py; do not edit by hand -->",
        "# 高频困惑点统计",
        "",
        f"数据源：`{source}`",
        "",
        "| 排名 | 概念 | 类别 | 章节 | 累计追问 | 最近日期 | 处置 |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for index, (tag, row) in enumerate(rows, start=1):
        action = "专项补讲" if row["count"] >= 2 else "观察"
        lines.append(
            f"| {index} | {tag} | {row['kind'] or '-'} | {row['chapter'] or '-'} "
            f"| {row['count']} | {row['last'] or '-'} | {action} |"
        )
    if not rows:
        lines.append("| - | 暂无记录 | - | - | - | - | - |")
    lines.extend(
        [
            "",
            "说明：累计追问 ≥ 2 的概念自动标为“专项补讲”；排序只反映提问频率，",
            "补讲优先级还需乘以考纲权重。",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", help="Path to records/confusions.jsonl")
    parser.add_argument("--output", help="Write Markdown here; default is stdout")
    parser.add_argument("--top", type=int, default=15, help="Rows to keep (default 15)")
    args = parser.parse_args()

    source = Path(args.input)
    if not source.is_file():
        parser.error(f"input not found: {source}")
    records, skipped = load(source)
    text = render(records, max(1, args.top), source)

    if args.output:
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8")
        print(f"wrote {output} ({len(records)} tags, skipped {skipped})")
    else:
        print(text)
        if skipped:
            print(f"# skipped {skipped} malformed line(s)", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
