#!/usr/bin/env python3
"""Build a mock-paper blueprint from dissected question JSONL.

Copies the real paper's structure instead of inventing one: one mock slot
per valid question, same type, points, difficulty and order. Each slot names
its 母题 (the original question) and the axis allowed to change (parameters
or wording), per references/error-taxonomy.md 变式协议. Rubric points are
allocated across `solution_skeleton`, so every score traces to a step.

Questions with `conf` < 0.90 are excluded. Missing type/points is a data
error (exit 1); missing skeleton/difficulty only yields a warning.

Usage:
  python mock_paper.py questions.jsonl [--out notes/MOCK-MID.md] [--title 期中模拟]
  python mock_paper.py questions.jsonl --json

Exit codes: 0 = blueprint built; 1 = 题目数据不足以组卷; 2 = 输入不可读。
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

BANNER = "<!-- generated by scripts/mock_paper.py; 结构复制原卷，rubric 由解法骨架折算 -->"
PENDING_CONF = 0.90


def as_float(value, default=0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def as_list(value) -> list[str]:
    if isinstance(value, list):
        return [str(v).strip() for v in value if str(v).strip()]
    if value in (None, ""):
        return []
    return [str(value).strip()]


def qid(row: dict) -> str:
    return f"{row.get('paper') or '?'}#{row.get('no') or '?'}"


def load(path: Path) -> tuple[list[dict], int]:
    rows, skipped = [], 0
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip():
            continue
        try:
            item = json.loads(line)
        except json.JSONDecodeError:
            skipped += 1
            continue
        if isinstance(item, dict):
            rows.append(item)
        else:
            skipped += 1
    return rows, skipped


def number_key(row: dict) -> tuple[int, str]:
    raw = str(row.get("no") or "")
    return (int(raw), raw) if raw.isdigit() else (10**6, raw)


def allocate(points: float, steps: list[str]) -> tuple[list[tuple[str, float]], str | None]:
    if not steps:
        return [], "缺 solution_skeleton，无法折算得分点，先补骨架"
    base = round(points / len(steps), 1)
    items = [(step, base) for step in steps]
    last = round(points - base * (len(steps) - 1), 1)
    items[-1] = (steps[-1], last)
    return items, None


def build(rows: list[dict], title: str) -> tuple[dict, list[str], list[str]]:
    warnings: list[str] = []
    errors: list[str] = []
    pending = [r for r in rows if as_float(r.get("conf"), 1.0) < PENDING_CONF]
    valid = [r for r in rows if as_float(r.get("conf"), 1.0) >= PENDING_CONF]
    for row in valid:
        missing = [key for key in ("type", "points") if row.get(key) in (None, "")]
        if missing:
            errors.append(f"{qid(row)} 缺 {missing}，不能组卷")
    if pending:
        warnings.append(f"剔除 {len(pending)} 道待核题（conf<{PENDING_CONF}），不进入模拟卷")

    types: dict[str, dict] = defaultdict(lambda: {"count": 0, "points": 0.0})
    for row in valid:
        name = str(row.get("type") or "未标").strip() or "未标"
        types[name]["count"] += 1
        types[name]["points"] += as_float(row.get("points"))

    slots = []
    for index, row in enumerate(sorted(valid, key=number_key), 1):
        points = as_float(row.get("points"))
        rubric, warning = allocate(points, as_list(row.get("solution_skeleton")))
        if warning:
            warnings.append(f"{qid(row)} {warning}")
        if not str(row.get("difficulty") or "").strip():
            warnings.append(f"{qid(row)} 缺 difficulty，难度栏显示「未标」")
        if not as_list(row.get("concepts")):
            warnings.append(f"{qid(row)} 缺 concepts，变式方向只能按原题骨架")
        slots.append({
            "mock_no": f"M{index}",
            "source": qid(row),
            "type": str(row.get("type") or "未标"),
            "points": points,
            "difficulty": str(row.get("difficulty") or "未标"),
            "concepts": as_list(row.get("concepts")),
            "textbook_ref": str(row.get("textbook_ref") or ""),
            "traps": as_list(row.get("traps")),
            "rubric": [{"step": step, "points": value} for step, value in rubric],
        })

    total = sum(as_float(row.get("points")) for row in valid)
    data = {
        "title": title,
        "questions": len(valid),
        "pending": len(pending),
        "points": total,
        "types": dict(types),
        "slots": slots,
        "warnings": warnings,
        "errors": errors,
    }
    return data, warnings, errors


def as_markdown(data: dict) -> str:
    lines = [BANNER, "", f"# 模拟卷组卷蓝图：{data['title']}", ""]
    lines.append(f"有效题 {data['questions']}，总分 {data['points']:g}；"
                 f"待核题 {data['pending']} 道已剔除。")
    lines.append("")

    lines.extend(["## 卷面结构", "", "| 题型 | 题量 | 分值 | 占比 |", "| --- | --- | --- | --- |"])
    for name, slot in sorted(data["types"].items(), key=lambda kv: (-kv[1]["points"], kv[0])):
        share = slot["points"] / data["points"] if data["points"] else 0
        lines.append(f"| {name} | {slot['count']} | {slot['points']:g} | {share:.0%} |")
    lines.append("")

    lines.extend([
        "## 组卷蓝图", "",
        "| 模拟题号 | 母题 | 题型 | 分值 | 难度 | 考点 | 教材节 | 变式要求 |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ])
    for slot in data["slots"]:
        concepts = "、".join(slot["concepts"]) or "-"
        lines.append(
            f"| {slot['mock_no']} | {slot['source']} | {slot['type']} | {slot['points']:g} | "
            f"{slot['difficulty']} | {concepts} | {slot['textbook_ref'] or '-'} | "
            "只改参数或表述，锁定考点/骨架/难度 |"
        )
    lines.append("")

    lines.extend(["## 评分细则", ""])
    for slot in data["slots"]:
        lines.append(f"### {slot['mock_no']}（母题 {slot['source']}，{slot['points']:g} 分）")
        lines.append("")
        if slot["rubric"]:
            lines.append("得分点：")
            for item in slot["rubric"]:
                lines.append(f"- {item['step']}（{item['points']:g} 分）")
        else:
            lines.append("得分点：待补 solution_skeleton 后再折算。")
        if slot["traps"]:
            lines.append("")
            lines.append("扣分点：" + "；".join(f"出现「{trap}」按错步扣分" for trap in slot["traps"]))
        lines.append("")

    if data["warnings"]:
        lines.extend(["## 数据自检", ""])
        lines.extend(f"- {item}" for item in data["warnings"])
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", help="已解剖的题目 JSONL")
    parser.add_argument("--title", default="模拟卷", help="模拟卷名称")
    parser.add_argument("--out", help="写入 Markdown（默认打印到标准输出）")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    path = Path(args.path)
    if not path.is_file():
        print(f"not a file: {path}", file=sys.stderr)
        return 2
    rows, skipped = load(path)
    if not rows:
        print(f"没有可用题目：{path}", file=sys.stderr)
        return 2

    data, warnings, errors = build(rows, args.title)
    if skipped:
        warnings.append(f"跳过 {skipped} 行无法解析的 JSON")
        data["warnings"] = warnings
    if not data["slots"]:
        print("没有 conf>=0.90 的有效题，无法组卷", file=sys.stderr)
        return 1

    text = json.dumps(data, ensure_ascii=False, indent=2) if args.json else as_markdown(data)
    if args.out:
        target = Path(args.out)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {target} slots={len(data['slots'])} points={data['points']:g}")
    else:
        print(text)

    for item in errors:
        print(item, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
