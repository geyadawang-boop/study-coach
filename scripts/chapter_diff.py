#!/usr/bin/env python3
"""Diff two chapter trees and mark questions retired by a new edition.

Sources: Markdown heading trees (`#`..`######`), PDF outlines read with
PyMuPDF (`doc.get_toc()`), or toc_extract.py JSON (`tree` array with page
numbers). Matching is by normalized title; a removed title with high
similarity to an added one is reported as a rename, not as delete+add. With
`--questions`, questions whose `textbook_ref` points at a removed or renamed
section are listed as 已退役 (G2: 教材版本管理).

Usage:
  python chapter_diff.py old.md new.md [--questions analyzed.jsonl] [--out diff.md]
  python chapter_diff.py old.pdf new.pdf --json

Exit codes: 0 = diff built; 2 = input unreadable or no headings/outline;
3 = 缺 PyMuPDF（读 PDF 目录时）。
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*$")
BANNER = "<!-- generated by scripts/chapter_diff.py; 章节树 diff，不手改 -->"
RENAME_RATIO = 0.60


def normalize(value: str) -> str:
    return re.sub(r"\s+", "", value).lower()


def load_tree(path: Path) -> list[dict]:
    if path.suffix.lower() == ".json":
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        rows = data.get("tree") if isinstance(data, dict) else data
        if not isinstance(rows, list):
            raise ValueError("JSON 需要 tree 数组（toc_extract.py 的输出）")
        tree = [
            {
                "level": int(item.get("level") or 1),
                "title": str(item.get("title") or "").strip(),
                "page": int(item["page"]) if item.get("page") else None,
            }
            for item in rows
            if isinstance(item, dict) and str(item.get("title") or "").strip()
        ]
    elif path.suffix.lower() == ".pdf":
        from fitz_compat import fitz  # PyMuPDF，经兼容层避免 1.28 弃用横幅污染 stdout

        with fitz.open(path) as doc:
            toc = doc.get_toc(simple=True)
        tree = [
            {"level": int(level), "title": str(title).strip(), "page": int(page) or None}
            for level, title, page in toc
        ]
    else:
        tree = []
        for line in path.read_text(encoding="utf-8-sig", errors="replace").splitlines():
            match = HEADING.match(line)
            if match:
                tree.append({
                    "level": len(match.group(1)),
                    "title": match.group(2).strip(),
                    "page": None,
                })
    if not tree:
        raise ValueError(
            "没有章节树：PDF 无内嵌目录或文件无标题；"
            "请先把印刷目录抄成 Markdown（`# 章` / `## 节`）再对比"
        )
    return tree


def keyed(tree: list[dict]) -> list[tuple[str, dict]]:
    """Key by ancestor path，避免各章重复的「本章小结」互相覆盖。"""
    out: list[tuple[str, dict]] = []
    stack: list[str] = []
    used: dict[str, int] = {}
    for item in tree:
        level = max(1, int(item.get("level") or 1))
        stack = stack[:level - 1]
        key = normalize(">".join(stack + [str(item["title"])]))
        count = used.get(key, 0) + 1
        used[key] = count
        if count > 1:
            key = f"{key}#{count}"
        out.append((key, item))
        stack = stack + [str(item["title"])]
    return out


def diff(old: list[dict], new: list[dict]) -> dict:
    old_pairs, new_pairs = keyed(old), keyed(new)
    old_keys = {key for key, _ in old_pairs}
    new_by = dict(new_pairs)
    matched = [(item, new_by[key]) for key, item in old_pairs if key in new_by]
    removed = [item for key, item in old_pairs if key not in new_by]
    added = [item for key, item in new_pairs if key not in old_keys]

    # 父章改名会改变子章路径：题名完全一致时仍视为同一节，避免冒充改名
    by_title: dict[str, list[dict]] = {}
    for item in added:
        by_title.setdefault(normalize(item["title"]), []).append(item)
    old_left: list[dict] = []
    for item in removed:
        candidates = by_title.get(normalize(item["title"]), [])
        if len(candidates) == 1:
            matched.append((item, candidates[0]))
            added.remove(candidates[0])
        else:
            old_left.append(item)
    removed = old_left

    renames: list[dict] = []
    for old_item in list(removed):
        best: tuple[float, dict] | None = None
        for new_item in added:
            ratio = difflib.SequenceMatcher(
                None, normalize(old_item["title"]), normalize(new_item["title"])
            ).ratio()
            if ratio >= RENAME_RATIO and (best is None or ratio > best[0]):
                best = (ratio, new_item)
        if best:
            renames.append({"old": old_item, "new": best[1], "ratio": round(best[0], 2)})
            removed.remove(old_item)
            added.remove(best[1])

    shifted = []
    for old_item, new_item in matched:
        if old_item.get("page") and new_item.get("page"):
            delta = new_item["page"] - old_item["page"]
            if delta:
                shifted.append({"title": new_item["title"],
                                "old": old_item["page"],
                                "new": new_item["page"],
                                "delta": delta})
    for pair in renames:
        old_page, new_page = pair["old"].get("page"), pair["new"].get("page")
        if old_page and new_page and new_page != old_page:
            shifted.append({"title": pair["new"]["title"],
                            "old": old_page,
                            "new": new_page,
                            "delta": new_page - old_page})

    return {"removed": removed, "added": added, "renames": renames, "shifted": shifted}


def affects(ref: str, titles: list[str]) -> bool:
    target = normalize(ref)
    if not target:
        return False
    return any(len(normalize(title)) >= 4 and
               (normalize(title) in target or target in normalize(title))
               for title in titles)


def retired_questions(path: Path, removed: list[dict], renames: list[dict]) -> tuple[list[dict], int]:
    old_titles = [item["title"] for item in removed] + [pair["old"]["title"] for pair in renames]
    rows: list[dict] = []
    skipped = 0
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip():
            continue
        try:
            item = json.loads(line)
        except json.JSONDecodeError:
            skipped += 1
            continue
        if not isinstance(item, dict):
            skipped += 1
            continue
        ref = str(item.get("textbook_ref") or "").strip()
        if ref and affects(ref, old_titles):
            rows.append({
                "id": f"{item.get('paper') or '?'}#{item.get('no') or '?'}",
                "textbook_ref": ref,
                "reason": "章节已删除" if any(affects(ref, [r["title"]]) for r in removed)
                          else "章节已改名",
            })
    return rows, skipped


def as_markdown(result: dict, old_path: Path, new_path: Path, retired: list[dict]) -> str:
    lines = [BANNER, "", f"# 章节版本对比：{old_path.name} → {new_path.name}", ""]
    lines.append(f"新增 {len(result['added'])}，删除 {len(result['removed'])}，"
                 f"疑似改名 {len(result['renames'])}，页码变化 {len(result['shifted'])}。")
    lines.append("")

    lines.extend(["## 新增章节", "", "| 层级 | 标题 | 页码 |", "| --- | --- | --- |"])
    for item in result["added"]:
        lines.append(f"| {item['level']} | {item['title']} | {item.get('page') or '-'} |")
    if not result["added"]:
        lines.append("| - | 无 | - |")
    lines.append("")

    lines.extend(["## 删除章节", "", "| 层级 | 标题 | 页码 |", "| --- | --- | --- |"])
    for item in result["removed"]:
        lines.append(f"| {item['level']} | {item['title']} | {item.get('page') or '-'} |")
    if not result["removed"]:
        lines.append("| - | 无 | - |")
    lines.append("")

    lines.extend(["## 疑似改名", "", "| 旧标题 | 新标题 | 相似度 |", "| --- | --- | --- |"])
    for pair in result["renames"]:
        lines.append(f"| {pair['old']['title']} | {pair['new']['title']} | {pair['ratio']:.2f} |")
    if not result["renames"]:
        lines.append("| - | - | - |")
    lines.append("")

    lines.extend(["## 页码变化", "", "| 标题 | 旧页 | 新页 | 偏移 |", "| --- | --- | --- | --- |"])
    for item in result["shifted"]:
        lines.append(f"| {item['title']} | {item['old']} | {item['new']} | {item['delta']:+d} |")
    if not result["shifted"]:
        lines.append("| - | - | - | - |")
    lines.append("")

    if retired:
        lines.extend(["## 已退役题", "", "| 题号 | 教材节 | 原因 |", "| --- | --- | --- |"])
        for row in retired:
            lines.append(f"| {row['id']} | {row['textbook_ref']} | {row['reason']} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("old", help="旧版 Markdown / PDF / toc.json")
    parser.add_argument("new", help="新版 Markdown / PDF / toc.json")
    parser.add_argument("--questions", help="题目 JSONL，用于标记已退役题")
    parser.add_argument("--out", help="写入 Markdown（默认打印到标准输出）")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    old_path, new_path = Path(args.old), Path(args.new)
    for path in (old_path, new_path):
        if not path.is_file():
            print(f"not a file: {path}", file=sys.stderr)
            return 2
    try:
        old_tree, new_tree = load_tree(old_path), load_tree(new_path)
    except ImportError:
        print("需要 PyMuPDF 才能读 PDF 目录：pip install pymupdf", file=sys.stderr)
        return 3
    except Exception as exc:  # 损坏、加密、无目录
        print(f"无法读取章节树（{type(exc).__name__}）：{exc}", file=sys.stderr)
        return 2

    result = diff(old_tree, new_tree)
    retired: list[dict] = []
    skipped = 0
    if args.questions:
        qpath = Path(args.questions)
        if not qpath.is_file():
            print(f"not a file: {qpath}", file=sys.stderr)
            return 2
        retired, skipped = retired_questions(qpath, result["removed"], result["renames"])

    if args.json:
        payload = {**result, "retired": retired, "skipped": skipped}
        text = json.dumps(payload, ensure_ascii=False, indent=2)
    else:
        text = as_markdown(result, old_path, new_path, retired)
        if skipped:
            text += f"\n跳过 {skipped} 行无法解析的题目 JSON。\n"
    if args.out:
        target = Path(args.out)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {target}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
