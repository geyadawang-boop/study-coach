#!/usr/bin/env python3
"""Render a whole-paper report from dissected question JSONL.

Every number in the report traces back to a question number
(`paper#no`). Questions with `conf` < 0.90 are listed under 待核 and
excluded from 考点分布 and 难度曲线, per references/paper-intake.md.

Input fields: paper, no, type, points, conf, concepts, textbook_ref,
difficulty, difficulty_basis, solution_skeleton, traps, parent.

Usage:
  python paper_report.py questions.jsonl [--paper MID-2025A] [--out notes/PAPER-MID.md]
  python paper_report.py questions.jsonl --json

Exit codes: 0 = report built; 1 = 数据自检不通过（总分/考点合计不一致）;
2 = 输入不可读。
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

BANNER = "<!-- generated by scripts/paper_report.py; 数据来自题目 JSONL，不手改 -->"
PENDING_CONF = 0.90


def load(path: Path) -> tuple[list[dict], int]:
    rows: list[dict] = []
    skipped = 0
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip():
            continue
        try:
            item = json.loads(line)
        except json.JSONDecodeError:
            skipped += 1
            continue
        if isinstance(item, dict):
            rows.append(item)
        else:
            skipped += 1
    return rows, skipped


def as_float(value, default=0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def qid(row: dict) -> str:
    return f"{row.get('paper') or '?'}#{row.get('no') or '?'}"


def as_list(value) -> list[str]:
    if isinstance(value, list):
        return [str(v).strip() for v in value if str(v).strip()]
    if value in (None, ""):
        return []
    return [str(value).strip()]


def build(rows: list[dict], paper: str | None) -> tuple[dict, list[str]]:
    warnings: list[str] = []
    if paper:
        rows = [r for r in rows if str(r.get("paper")) == paper]
        if not rows:
            warnings.append(f"没有 paper={paper} 的题目")

    pending = [r for r in rows if as_float(r.get("conf"), 1.0) < PENDING_CONF]
    pending_ids = {id(r) for r in pending}
    valid = [r for r in rows if id(r) not in pending_ids]
    total_points = sum(as_float(r.get("points")) for r in rows)
    valid_points = sum(as_float(r.get("points")) for r in valid)

    types: dict[str, dict] = {}
    for row in rows:
        name = str(row.get("type") or "未标").strip() or "未标"
        slot = types.setdefault(name, {"count": 0, "points": 0.0, "nos": []})
        slot["count"] += 1
        slot["points"] += as_float(row.get("points"))
        slot["nos"].append(str(row.get("no") or "?"))

    concepts: dict[str, dict] = {}
    for row in valid:
        names = as_list(row.get("concepts"))
        if not names:
            slot = concepts.setdefault("未归类", {"nos": [], "points": 0.0, "refs": set()})
            slot["nos"].append(str(row.get("no") or "?"))
            slot["points"] += as_float(row.get("points"))
            continue
        for name in names:
            slot = concepts.setdefault(name, {"nos": [], "points": 0.0, "refs": set()})
            slot["nos"].append(str(row.get("no") or "?"))
            slot["points"] += as_float(row.get("points"))
            ref = str(row.get("textbook_ref") or "").strip()
            if ref:
                slot["refs"].add(ref)

    difficulty: list[dict] = []
    for row in valid:
        level = str(row.get("difficulty") or "").strip() or "未标"
        basis = str(row.get("difficulty_basis") or "").strip()
        if not basis:
            steps = as_list(row.get("solution_skeleton"))
            basis = f"步骤 {len(steps)} 步" if steps else ""
        if not basis:
            warnings.append(f"{qid(row)} 的 difficulty 缺依据（步骤数/构造/真题频率）")
        difficulty.append({"no": str(row.get("no") or "?"), "level": level, "basis": basis or "缺依据"})

    traps: dict[str, list[str]] = defaultdict(list)
    for row in valid:
        for trap in as_list(row.get("traps")):
            traps[trap].append(str(row.get("no") or "?"))

    parents: dict[str, list[str]] = defaultdict(list)
    for row in rows:
        parent = str(row.get("parent") or "").strip()
        if parent:
            parents[parent].append(str(row.get("no") or "?"))

    classified_points = sum(
        as_float(r.get("points")) for r in valid if as_list(r.get("concepts"))
    )
    if valid and classified_points != valid_points:
        warnings.append(
            f"考点分值合计 {classified_points:g} != 有效题总分 {valid_points:g}（有题未归类）"
        )
    missing_difficulty = sum(1 for row in valid if not str(row.get("difficulty") or "").strip())
    if missing_difficulty:
        warnings.append(f"{missing_difficulty} 题缺 difficulty，难度曲线显示「未标」")

    report = {
        "paper": paper or (str(rows[0].get("paper")) if rows else ""),
        "questions": len(rows),
        "points": total_points,
        "valid": len(valid),
        "valid_points": valid_points,
        "pending": [{"no": str(r.get("no") or "?"), "conf": as_float(r.get("conf"))} for r in pending],
        "types": types,
        "concepts": {k: {"nos": v["nos"], "points": v["points"], "refs": sorted(v["refs"])}
                     for k, v in concepts.items()},
        "difficulty": difficulty,
        "traps": dict(traps),
        "parents": dict(parents),
        "warnings": warnings,
    }
    return report, warnings


def cell(value) -> str:
    """Markdown 表格单元：竖线转义、换行压平，避免整张表错列。"""
    return str(value).replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def as_markdown(report: dict) -> str:
    lines = [BANNER, "", f"# 整卷报告 {report['paper'] or '（未标卷别）'}", ""]
    lines.append(f"题数 {report['questions']}，总分 {report['points']:g}；"
                 f"有效题 {report['valid']}（{report['valid_points']:g} 分），"
                 f"待核 {len(report['pending'])}。")
    lines.append("")

    lines.extend(["## 卷面结构", "", "| 题型 | 题数 | 分值 | 占比 |", "| --- | --- | --- | --- |"])
    for name, slot in sorted(report["types"].items(), key=lambda kv: (-kv[1]["points"], kv[0])):
        share = slot["points"] / report["points"] if report["points"] else 0
        lines.append(f"| {cell(name)} | {slot['count']} | {slot['points']:g} | {share:.0%} |")
    lines.append("")

    lines.extend(["## 考点分布", "", "| 考点 | 题号 | 分值合计 | 教材节 |", "| --- | --- | --- | --- |"])
    for name, slot in sorted(report["concepts"].items(), key=lambda kv: (-kv[1]["points"], kv[0])):
        lines.append(
            f"| {cell(name)} | {', '.join(slot['nos'])} | {slot['points']:g} | "
            f"{cell('; '.join(slot['refs']) or '-')} |"
        )
    if not report["concepts"]:
        lines.append("| - | - | - | 暂无解剖数据 |")
    lines.append("")

    lines.extend(["## 难度曲线", "", "| 题号 | 难度 | 依据 |", "| --- | --- | --- |"])
    for row in report["difficulty"]:
        lines.append(f"| {row['no']} | {row['level']} | {cell(row['basis'])} |")
    if not report["difficulty"]:
        lines.append("| - | - | 暂无有效题 |")
    lines.append("")

    lines.extend(["## 陷阱清单", "", "| 陷阱 | 题号 | 后果 |", "| --- | --- | --- |"])
    for trap, nos in sorted(report["traps"].items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines.append(f"| {cell(trap)} | {', '.join(nos)} | 丢分 |")
    if not report["traps"]:
        lines.append("| - | - | 暂无标注 |")
    lines.append("")

    lines.extend(["## 高频母题", "", "| 母题 | 出现题号 | 变式方向 |", "| --- | --- | --- |"])
    for parent, nos in sorted(report["parents"].items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines.append(f"| {parent} | {', '.join(nos)} | 换参数/改条件，先验证同构 |")
    if not report["parents"]:
        lines.append("| - | - | 暂无 parent 标注 |")
    lines.append("")

    if report["pending"]:
        lines.extend(["## 待核题", "", "| 题号 | conf |", "| --- | --- |"])
        for row in report["pending"]:
            lines.append(f"| {row['no']} | {row['conf']:.2f} |")
        lines.append("")
        lines.append("待核题不进入考点分布与难度曲线，先补清晰照片或原页。")
        lines.append("")

    if report["warnings"]:
        lines.extend(["## 数据自检", ""])
        for item in report["warnings"]:
            lines.append(f"- {item}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", help="题目 JSONL（含解剖字段）")
    parser.add_argument("--paper", help="只报告该卷别")
    parser.add_argument("--out", help="写入 Markdown 路径（默认打印到标准输出）")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    path = Path(args.path)
    if not path.is_file():
        print(f"not a file: {path}", file=sys.stderr)
        return 2
    rows, skipped = load(path)
    if not rows:
        print(f"没有可用题目：{path}", file=sys.stderr)
        return 2

    report, warnings = build(rows, args.paper)
    if skipped:
        warnings.append(f"跳过 {skipped} 行无法解析的 JSON")
        report["warnings"] = warnings

    if args.json:
        text = json.dumps(report, ensure_ascii=False, indent=2)
    else:
        text = as_markdown(report)
    if args.out:
        target = Path(args.out)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {target}")
    else:
        print(text)

    return 1 if any("不一致" in w or "!=" in w for w in warnings) else 0


if __name__ == "__main__":
    raise SystemExit(main())
