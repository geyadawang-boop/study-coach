#!/usr/bin/env python3
"""Build a one-page A4 cheat sheet from cards, mistakes and confusions.

Borrowed from the 速查表 SOP in the open study toolkit. A cheat sheet is not a
compressed note: it only keeps what is used in the exam and easy to forget.

Four blocks, all required:
  1. 核心公式与条件  — 定理/步骤卡，公式必须同格写适用条件
  2. 易混对照        — 陷阱卡 + 高频困惑
  3. 识别信号        — 看到 X → 想到 Y
  4. 陷阱清单        — 来自真实错题，按重复次数排序

定义原文、推导、例题不进速查表；页面按 A4 黑白打印设计。

Usage:
  python cheatsheet.py --kb 学习库
  python cheatsheet.py --kb 学习库 --max-formulas 6 --format html --json

Exit codes: 0 = written; 1 = missing both 易混对照 and 陷阱 (sheet fails the
SOP gate); 2 = missing knowledge base.
"""

from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path


def load_jsonl(path: Path) -> tuple[list[dict], int]:
    rows: list[dict] = []
    skipped = 0
    if not path.is_file():
        return rows, skipped
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip():
            continue
        try:
            item = json.loads(line)
        except json.JSONDecodeError:
            skipped += 1
            continue
        if isinstance(item, dict):
            rows.append(item)
        else:
            skipped += 1
    return rows, skipped


def text_of(value: object) -> str:
    if isinstance(value, list):
        return "；".join(str(v) for v in value if str(v).strip())
    return str(value or "").strip()


def build_data(kb: Path, limits: dict) -> tuple[dict, dict]:
    cards, bad_cards = load_jsonl(kb / "records/cards.jsonl")
    errors, bad_errors = load_jsonl(kb / "records/errors.jsonl")
    confusions, bad_conf = load_jsonl(kb / "records/confusions.jsonl")

    active = [c for c in cards if str(c.get("status", "")).lower() != "retired"]

    formulas = []
    for card in active:
        if card.get("type") not in {"定理", "步骤"}:
            continue
        method = text_of(card.get("method"))
        if not method:
            continue
        formulas.append({
            "title": text_of(card.get("title")) or text_of(card.get("id")),
            "method": method,
            "condition": text_of(card.get("boundary")) or "条件待补",
        })
    formulas = formulas[: limits["max_formulas"]]

    confus = []
    for card in active:
        if card.get("type") != "陷阱":
            continue
        confus.append({
            "left": text_of(card.get("title")) or text_of(card.get("id")),
            "right": text_of(card.get("boundary")) or "边界待补",
            "signal": text_of(card.get("signal")) or "-",
        })
    for item in sorted(confusions, key=lambda x: int(x.get("ask_count") or 0), reverse=True):
        tag = text_of(item.get("tag"))
        if not tag:
            continue
        confus.append({
            "left": tag,
            "right": text_of(item.get("note")) or "待补",
            "signal": text_of(item.get("kind")) or "困惑",
        })
    confus = confus[: limits["max_confusions"]]

    signals = []
    for card in active:
        sig = text_of(card.get("signal"))
        if not sig:
            continue
        signals.append({
            "signal": sig,
            "action": text_of(card.get("title")) or text_of(card.get("id")),
            "method": text_of(card.get("method")) or "方法待补",
        })
    signals = signals[: limits["max_signals"]]

    traps = []
    for item in errors:
        if str(item.get("status", "")).lower() in {"closed", "fixed", "retired"}:
            continue
        traps.append({
            "desc": text_of(item.get("desc")),
            "fix": text_of(item.get("fix")) or "修法待补",
            "count": int(item.get("count") or 1),
            "ref": text_of(item.get("id")),
        })
    traps.sort(key=lambda x: (-x["count"], x["ref"]))
    traps = traps[: limits["max_traps"]]

    data = {"formulas": formulas, "confusions": confus, "signals": signals, "traps": traps}
    meta = {
        "skippedLines": bad_cards + bad_errors + bad_conf,
        "cards": len(active),
        "errors": len(errors),
        "confusions": len(confusions),
    }
    return data, meta


def table_md(headers: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        out.append("| " + " | ".join(cell.replace("|", "/") for cell in row) + " |")
    return out


def render_md(data: dict) -> str:
    lines = [
        "<!-- generated by scripts/cheatsheet.py; do not edit by hand -->",
        "",
        "# 一页速查表",
        "",
        "> 由 `scripts/cheatsheet.py` 从 `records/` 生成，不手改。",
        "> 只收考场要用、平时会忘的内容；定义原文、推导与例题不收。",
        "",
        "## 一、核心公式与条件",
        "",
    ]
    if data["formulas"]:
        lines += table_md(
            ["公式 / 方法", "适用条件", "常见误用"],
            [[f["title"], f["condition"], f["method"]] for f in data["formulas"]],
        )
    else:
        lines.append("- 暂无定理/步骤卡。")

    lines += ["", "## 二、易混对照", ""]
    if data["confusions"]:
        lines += table_md(
            ["A", "B / 边界", "判定信号"],
            [[c["left"], c["right"], c["signal"]] for c in data["confusions"]],
        )
    else:
        lines.append("- 暂无陷阱卡与困惑记录。")

    lines += ["", "## 三、识别信号", ""]
    if data["signals"]:
        lines += table_md(
            ["看到", "想到", "先做什么"],
            [[s["signal"], s["action"], s["method"]] for s in data["signals"]],
        )
    else:
        lines.append("- 暂无带 signal 的卡片。")

    lines += ["", "## 四、陷阱清单", ""]
    if data["traps"]:
        for i, trap in enumerate(data["traps"], 1):
            lines.append(f"{i}. {trap['desc']}（{trap['ref']}，{trap['count']} 次）—— {trap['fix']}")
    else:
        lines.append("- 暂无未闭环错题。")

    lines += [
        "",
        "## 自检",
        "",
        "- 四区齐全；公式与条件同格；",
        "- 表格优先，每行一个信息点；",
        "- 黑白打印不依赖颜色；",
        "- 超过一页时按“用到的概率 × 忘掉的概率”从低到高删。",
    ]
    return "\n".join(lines) + "\n"


CSS = """
@page { size: A4 portrait; margin: 10mm; }
body { font-family: "Microsoft YaHei", "Noto Sans CJK SC", Arial, sans-serif;
       color: #111; margin: 0; font-size: 9.5pt; line-height: 1.45; }
h1 { font-size: 16pt; margin: 0 0 4mm; border-bottom: 2px solid #111; padding-bottom: 2mm; }
h2 { font-size: 11pt; margin: 4mm 0 2mm; border-left: 4px solid #111; padding-left: 2mm; }
table { border-collapse: collapse; width: 100%; margin-bottom: 2mm; }
th, td { border: 0.4pt solid #555; padding: 1.2mm 1.6mm; vertical-align: top; }
th { background: #eee; font-weight: 700; text-align: left; }
ol { margin: 0 0 2mm 5mm; padding: 0; }
p.note { color: #444; font-size: 8pt; margin: 0 0 3mm; }
"""


def esc(value: object) -> str:
    return html.escape(str(value or ""), quote=False)


def html_table(headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{esc(cell)}</td>" for cell in row) + "</tr>" for row in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def render_html(data: dict) -> str:
    parts = [
        "<!DOCTYPE html><html lang=\"zh-CN\"><head><meta charset=\"utf-8\">",
        "<title>一页速查表</title><style>", CSS, "</style></head><body>",
        "<h1>一页速查表</h1>",
        '<p class="note">由 scripts/cheatsheet.py 生成。只收考场要用、平时会忘的内容；黑白打印。</p>',
        "<h2>一、核心公式与条件</h2>",
    ]
    if data["formulas"]:
        parts.append(html_table(
            ["公式 / 方法", "适用条件", "常见误用"],
            [[f["title"], f["condition"], f["method"]] for f in data["formulas"]],
        ))
    else:
        parts.append("<p>暂无定理/步骤卡。</p>")

    parts.append("<h2>二、易混对照</h2>")
    if data["confusions"]:
        parts.append(html_table(
            ["A", "B / 边界", "判定信号"],
            [[c["left"], c["right"], c["signal"]] for c in data["confusions"]],
        ))
    else:
        parts.append("<p>暂无陷阱卡与困惑记录。</p>")

    parts.append("<h2>三、识别信号</h2>")
    if data["signals"]:
        parts.append(html_table(
            ["看到", "想到", "先做什么"],
            [[s["signal"], s["action"], s["method"]] for s in data["signals"]],
        ))
    else:
        parts.append("<p>暂无带 signal 的卡片。</p>")

    parts.append("<h2>四、陷阱清单</h2>")
    if data["traps"]:
        items = "".join(
            f"<li>{esc(t['desc'])}（{esc(t['ref'])}，{t['count']} 次）—— {esc(t['fix'])}</li>"
            for t in data["traps"]
        )
        parts.append(f"<ol>{items}</ol>")
    else:
        parts.append("<p>暂无未闭环错题。</p>")

    parts.append("</body></html>")
    return "".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kb", required=True, help="学习库根目录")
    parser.add_argument("--outdir", help="输出目录，默认 <kb>/views")
    parser.add_argument("--format", choices=("md", "html", "both"), default="both")
    parser.add_argument("--max-formulas", type=int, default=8)
    parser.add_argument("--max-confusions", type=int, default=4)
    parser.add_argument("--max-signals", type=int, default=8)
    parser.add_argument("--max-traps", type=int, default=5)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    kb = Path(args.kb)
    if not kb.is_dir():
        print(f"学习库不存在：{kb}", file=sys.stderr)
        return 2
    limits = {
        "max_formulas": max(0, args.max_formulas),
        "max_confusions": max(0, args.max_confusions),
        "max_signals": max(0, args.max_signals),
        "max_traps": max(0, args.max_traps),
    }
    data, meta = build_data(kb, limits)
    md = render_md(data)
    html_text = render_html(data)
    outdir = Path(args.outdir) if args.outdir else kb / "views"
    md_path = outdir / "速查表.md"
    html_path = outdir / "速查表.html"
    if not args.dry_run:
        outdir.mkdir(parents=True, exist_ok=True)
        if args.format in {"md", "both"}:
            md_path.write_text(md, encoding="utf-8")
        if args.format in {"html", "both"}:
            html_path.write_text(html_text, encoding="utf-8")

    gate = bool(data["confusions"] or data["traps"])
    summary = {
        "kb": kb.as_posix(),
        "md": md_path.as_posix(),
        "html": html_path.as_posix(),
        "counts": {key: len(value) for key, value in data.items()},
        "gate": gate,
        "skippedLines": meta["skippedLines"],
        "bytes": len(md.encode("utf-8")) + len(html_text.encode("utf-8")),
        "dryRun": args.dry_run,
    }
    if args.json:
        print(json.dumps(summary, ensure_ascii=False, indent=2))
    else:
        print(
            f"formulas={summary['counts']['formulas']} confusions={summary['counts']['confusions']} "
            f"signals={summary['counts']['signals']} traps={summary['counts']['traps']} -> {outdir}"
        )
    if not gate:
        print("不合格：缺易混对照与陷阱清单，按速查表 SOP 不能交付", file=sys.stderr)
    return 0 if gate else 1


if __name__ == "__main__":
    raise SystemExit(main())
