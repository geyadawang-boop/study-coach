#!/usr/bin/env python3
"""Build a weekly learning report from append-only records.

Reads records/*.jsonl within a date window and renders one Markdown
report. Every number traces back to a record file; missing files or empty
windows produce zeros plus an explicit 自检 warning instead of invented
content.

Usage:
  python weekly_report.py --kb 学习库 [--end 2026-11-08] [--days 7]
  python weekly_report.py --kb 学习库 --out views/周报-2026-11-08.md --json

Exit codes: 0 = report built; 2 = kb 目录不存在。
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from datetime import date, timedelta
from pathlib import Path

BANNER = "<!-- generated by scripts/weekly_report.py; 数据来自 records/，不手改 -->"


def load(path: Path) -> tuple[list[dict], int]:
    rows: list[dict] = []
    skipped = 0
    if not path.exists():
        return rows, skipped
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip():
            continue
        try:
            item = json.loads(line)
        except json.JSONDecodeError:
            skipped += 1
            continue
        if isinstance(item, dict):
            rows.append(item)
        else:
            skipped += 1
    return rows, skipped


def day_of(value) -> date | None:
    try:
        return date.fromisoformat(str(value or "")[:10])
    except ValueError:
        return None


def as_float(value, default=0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def build(kb: Path, end: date, days: int) -> tuple[dict, list[str]]:
    warnings: list[str] = []
    start = end - timedelta(days=days - 1)
    buckets: dict[str, list[dict]] = {}
    for name in ("events", "reviews", "errors", "confusions", "cards", "sources"):
        rows, skipped = load(kb / "records" / f"{name}.jsonl")
        buckets[name] = rows
        if skipped:
            warnings.append(f"records/{name}.jsonl 有 {skipped} 行无法解析，已跳过")

    in_window = lambda value: (  # noqa: E731
        (parsed := day_of(value)) is not None and start <= parsed <= end
    )

    events = [row for row in buckets["events"] if in_window(row.get("ts"))]
    reviews = [row for row in buckets["reviews"] if in_window(row.get("ts"))]
    errors = [row for row in buckets["errors"]
              if in_window(row.get("ts")) or in_window(row.get("first_seen"))]
    confusions = [row for row in buckets["confusions"] if in_window(row.get("date"))]
    cards = [row for row in buckets["cards"] if in_window(row.get("ts"))]
    sources = [row for row in buckets["sources"] if in_window(row.get("added_at"))]

    if not any((events, reviews, errors, confusions, cards, sources)):
        warnings.append(f"{start}..{end} 窗口内没有任何记录")

    actions = Counter(str(row.get("action") or "未标") for row in events)
    tickets = Counter(
        str(row.get("result") or "未标")
        for row in events if str(row.get("action")) == "exit_ticket"
    )

    ratings = [int(as_float(row.get("rating"))) for row in reviews
               if as_float(row.get("rating")) > 0]
    rating_dist = Counter(ratings)
    step_stats: dict[int, list[float]] = defaultdict(list)
    latest_due: dict[str, tuple[tuple[date, int], date]] = {}
    for order, row in enumerate(buckets["reviews"]):
        card = str(row.get("card_id") or "")
        due = day_of(row.get("due"))
        seen = day_of(row.get("ts"))
        if card and due and (seen is None or seen <= end):
            # 卡片可能被推迟：以 ts 最后一条 review 的 due 为准，文件名顺序不算数
            key = (seen or date.min, order)
            if card not in latest_due or key >= latest_due[card][0]:
                latest_due[card] = (key, due)
    for row in reviews:  # 只统计窗口内的步骤分，避免历史拉低本周均分
        for index, score in enumerate(row.get("step_scores") or [], 1):
            if isinstance(score, (int, float)):
                step_stats[index].append(float(score))
    due_cards = sorted(card for card, (_, due) in latest_due.items() if due <= end)

    step_rows = [
        {"step": index, "avg": sum(scores) / len(scores), "n": len(scores)}
        for index, scores in sorted(step_stats.items())
    ]
    weakest = min(step_rows, key=lambda row: row["avg"]) if step_rows else None

    open_errors = [row for row in buckets["errors"]
                   if str(row.get("status", "open")).lower() != "closed"]
    top_errors = sorted(open_errors, key=lambda row: -int(as_float(row.get("count"), 1)))[:5]

    tag_counts: Counter[str] = Counter()
    for row in confusions:
        tag_counts[str(row.get("tag") or "未标")] += int(as_float(row.get("ask_count"), 1))

    report = {
        "window": {"start": start.isoformat(), "end": end.isoformat(), "days": days},
        "kb": str(kb),
        "events": {"total": len(events), "actions": dict(actions), "tickets": dict(tickets)},
        "reviews": {
            "total": len(reviews),
            "avg_rating": round(sum(ratings) / len(ratings), 2) if ratings else None,
            "rating_dist": {str(k): v for k, v in sorted(rating_dist.items())},
            "steps": step_rows,
            "weakest_step": weakest,
            "due": due_cards[:10],
            "due_count": len(due_cards),
        },
        "errors": {
            "new": len(errors),
            "open_total": len(open_errors),
            "top": [{"id": row.get("id"), "concept": row.get("concept"),
                     "count": int(as_float(row.get("count"), 1))} for row in top_errors],
        },
        "confusions": {"new": len(confusions), "tags": dict(tag_counts.most_common(5))},
        "cards": {"new": len(cards)},
        "sources": {"new": len(sources)},
        "warnings": warnings,
    }
    return report, warnings


def as_markdown(report: dict) -> str:
    window = report["window"]
    lines = [BANNER, "", f"# 学习周报 {window['start']} ~ {window['end']}", ""]
    lines.append(
        f"事件 {report['events']['total']}；复习 {report['reviews']['total']}；"
        f"新增错题 {report['errors']['new']}；新增困惑 {report['confusions']['new']}；"
        f"新增卡片 {report['cards']['new']}；新增资料 {report['sources']['new']}。"
    )
    lines.append("")
    lines.append("## 事件与退出票")
    lines.append("")
    if report["events"]["actions"]:
        for name, count in sorted(report["events"]["actions"].items(), key=lambda kv: -kv[1]):
            lines.append(f"- {name}：{count}")
    else:
        lines.append("- 本周无事件记录")
    if report["events"]["tickets"]:
        passed = report["events"]["tickets"].get("pass", 0)
        failed = report["events"]["tickets"].get("fail", 0)
        lines.append(f"- 退出票：通过 {passed} / 未通过 {failed}")
    lines.append("")

    lines.append("## 复习")
    lines.append("")
    if report["reviews"]["total"]:
        avg = report["reviews"]["avg_rating"]
        lines.append(f"- 平均 rating：{avg if avg is not None else '无评分'}")
        dist = report["reviews"]["rating_dist"]
        lines.append("- 分布：" + "，".join(f"{k} 分 {v} 次" for k, v in dist.items()))
        weakest = report["reviews"]["weakest_step"]
        if weakest:
            lines.append(
                f"- 最弱步骤：第 {weakest['step']} 步（均分 {weakest['avg']:.2f}，{weakest['n']} 次）"
            )
    else:
        lines.append("- 本周无复习记录")
    if report["reviews"]["due_count"]:
        lines.append(
            f"- 已到期卡片：{report['reviews']['due_count']} 张（"
            + "、".join(report["reviews"]["due"]) + "）"
        )
    lines.append("")

    lines.append("## 错题与困惑")
    lines.append("")
    lines.append(f"- 未闭环错题：{report['errors']['open_total']} 条；本周新增 {report['errors']['new']} 条")
    for row in report["errors"]["top"]:
        lines.append(f"- {row['id']}｜{row['concept'] or '-'}：出现 {row['count']} 次")
    if report["confusions"]["tags"]:
        lines.append("- 高频困惑：" + "，".join(
            f"{tag} {count} 次" for tag, count in report["confusions"]["tags"].items()
        ))
    else:
        lines.append("- 本周无困惑记录")
    lines.append("")

    if report["warnings"]:
        lines.extend(["## 数据自检", ""])
        for item in report["warnings"]:
            lines.append(f"- {item}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kb", required=True, help="学习库根目录")
    parser.add_argument("--end", default=date.today().isoformat(), help="窗口结束日（含）")
    parser.add_argument("--days", type=int, default=7, help="窗口天数")
    parser.add_argument("--out", help="写入 Markdown 路径（默认打印到标准输出）")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    kb = Path(args.kb)
    if not kb.is_dir():
        print(f"kb not found: {kb}", file=sys.stderr)
        return 2
    try:
        end = date.fromisoformat(args.end)
    except ValueError:
        print(f"--end 不是 YYYY-MM-DD：{args.end}", file=sys.stderr)
        return 2

    report, _ = build(kb, end, max(1, args.days))
    text = json.dumps(report, ensure_ascii=False, indent=2) if args.json else as_markdown(report)
    if args.out:
        target = Path(args.out)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {target}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
